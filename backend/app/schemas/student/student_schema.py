from __future__ import annotations

from datetime import date
from uuid import UUID

from pydantic import (
    ConfigDict,
    EmailStr,
    Field,
    field_validator,
)

from app.common.enums.student import (
    BloodGroup,
    Gender,
    StudentStatus,
)
from app.schemas.base import (
    BaseResponseSchema,
    BaseSchema,
)


# ==========================================================
# Student Base
# ==========================================================


class StudentBase(BaseSchema):
    """
    Common student fields shared by Create and Update schemas.
    """

    # ------------------------------------------------------
    # Personal Information
    # ------------------------------------------------------

    first_name: str = Field(
        ...,
        min_length=2,
        max_length=100,
    )

    middle_name: str | None = Field(
        default=None,
        max_length=100,
    )

    last_name: str = Field(
        ...,
        min_length=1,
        max_length=100,
    )

    gender: Gender

    blood_group: BloodGroup | None = None

    date_of_birth: date

    # ------------------------------------------------------
    # Contact Information
    # ------------------------------------------------------

    email: EmailStr | None = None

    phone: str | None = Field(
        default=None,
        max_length=15,
    )

    emergency_contact: str | None = Field(
        default=None,
        max_length=15,
    )

    # ------------------------------------------------------
    # Address
    # ------------------------------------------------------

    address_line1: str = Field(
        ...,
        max_length=255,
    )

    address_line2: str | None = Field(
        default=None,
        max_length=255,
    )

    city: str = Field(
        ...,
        max_length=100,
    )

    district: str = Field(
        ...,
        max_length=100,
    )

    state: str = Field(
        ...,
        max_length=100,
    )

    country: str = Field(
        ...,
        max_length=100,
    )

    postal_code: str = Field(
        ...,
        max_length=10,
    )

    # ------------------------------------------------------
    # Academic Information
    # ------------------------------------------------------

    school_id: UUID

    parent_id: UUID

    academic_year_id: UUID

    school_class_id: UUID

    section_id: UUID

    admission_date: date

    status: StudentStatus = StudentStatus.ACTIVE

    # ------------------------------------------------------
    # Other
    # ------------------------------------------------------

    profile_photo_url: str | None = Field(
        default=None,
        max_length=500,
    )

    remarks: str | None = Field(
        default=None,
        max_length=500,
    )

    # ======================================================
    # Validators
    # ======================================================

    @field_validator("date_of_birth")
    @classmethod
    def validate_date_of_birth(
        cls,
        value: date,
    ) -> date:
        if value > date.today():
            raise ValueError(
                "Date of birth cannot be in the future."
            )

        return value

    @field_validator("admission_date")
    @classmethod
    def validate_admission_date(
        cls,
        value: date,
    ) -> date:
        if value > date.today():
            raise ValueError(
                "Admission date cannot be in the future."
            )

        return value

    @field_validator(
        "phone",
        "emergency_contact",
    )
    @classmethod
    def validate_phone_numbers(
        cls,
        value: str | None,
    ) -> str | None:
        if value is None:
            return value

        digits = (
            value.replace(" ", "")
            .replace("-", "")
        )

        if not digits.isdigit():
            raise ValueError(
                "Phone number must contain only digits."
            )

        if len(digits) < 10:
            raise ValueError(
                "Phone number must contain at least 10 digits."
            )

        if len(digits) > 15:
            raise ValueError(
                "Phone number cannot exceed 15 digits."
            )

        return digits



class StudentUpdate(BaseSchema):
    """
    Partial student update schema.
    """

    model_config = ConfigDict(
        extra="forbid",
    )

    # ------------------------------------------------------
    # Personal Information
    # ------------------------------------------------------

    first_name: Optional[str] = Field(
        default=None,
        min_length=2,
        max_length=100,
    )

    middle_name: Optional[str] = Field(
        default=None,
        max_length=100,
    )

    last_name: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=100,
    )

    gender: Optional[Gender] = None

    blood_group: Optional[BloodGroup] = None

    date_of_birth: Optional[date] = None

    # ------------------------------------------------------
    # Contact
    # ------------------------------------------------------

    email: Optional[EmailStr] = None

    phone: Optional[str] = None

    emergency_contact: Optional[str] = None

    # ------------------------------------------------------
    # Address
    # ------------------------------------------------------

    address_line1: Optional[str] = None

    address_line2: Optional[str] = None

    city: Optional[str] = None

    district: Optional[str] = None

    state: Optional[str] = None

    country: Optional[str] = None

    postal_code: Optional[str] = None

    # ------------------------------------------------------
    # Academic
    # ------------------------------------------------------

    parent_id: Optional[UUID] = None

    school_class_id: Optional[UUID] = None

    section_id: Optional[UUID] = None

    admission_date: Optional[date] = None

    status: Optional[StudentStatus] = None

    # ------------------------------------------------------
    # Other
    # ------------------------------------------------------

    profile_photo_url: Optional[str] = None

    remarks: Optional[str] = None

    @field_validator("date_of_birth")
    @classmethod
    def validate_date_of_birth(cls, value: Optional[date]):
        if value and value > date.today():
            raise ValueError("Date of birth cannot be in the future.")
        return value

    @field_validator("admission_date")
    @classmethod
    def validate_admission_date(cls, value: Optional[date]):
        if value and value > date.today():
            raise ValueError("Admission date cannot be in the future.")
        return value

    @field_validator("phone", "emergency_contact")
    @classmethod
    def validate_phone_numbers(cls, value: Optional[str]):
        if value is None:
            return value

        digits = value.replace(" ", "").replace("-", "")

        if not digits.isdigit():
            raise ValueError("Phone number must contain only digits.")

        if len(digits) < 10 or len(digits) > 15:
            raise ValueError("Invalid phone number.")

        return digits



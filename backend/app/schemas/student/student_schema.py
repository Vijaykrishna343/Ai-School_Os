# Filter
# ==========================================================


class StudentFilter(BaseSchema):
    """
    Student search and filter schema.
    """

    search: str | None = Field(
        default=None,
        max_length=100,
    )

    school_id: UUID | None = None

    academic_year_id: UUID | None = None

    school_class_id: UUID | None = None

    section_id: UUID | None = None

    parent_id: UUID | None = None

    gender: Gender | None = None

    status: StudentStatus | None = None

    page: int = Field(
        default=1,
        ge=1,
    )

    page_size: int = Field(
        default=10,
        ge=1,
        le=100,
    )

    sort_by: str = Field(
        default="created_at",
        max_length=50,
    )

    sort_order: str = Field(
        default="desc",
        pattern="^(asc|desc)$",
    )


